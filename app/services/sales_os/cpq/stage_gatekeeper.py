"""Enterprise Deal Stage Transition Gatekeeper.

Enforces deterministic criteria before moving deals between pipeline stages:
1. Pre-condition assertions (contacts verified, champion identified, approved quote, payment terms).
2. Prevents dual-state drift: atomically synchronizes DealRoom, SalesOpportunity, and Lead.
3. Immutable DealActivity audit logging for every stage transition.
"""
from typing import Dict, Any, List, Tuple, Optional
from sqlalchemy.orm import Session
from datetime import datetime, timezone

from app.models.deal_room import DealRoom, BuyingCommitteeMember, DealActivity
from app.models.sales_intelligence import SalesOpportunity, SalesCompany
from app.models.verticals import Lead


VALID_STAGES = [
    "discovered",
    "qualified",
    "researching",
    "outreach_ready",
    "in_cadence",
    "replied",
    "meeting_booked",
    "proposal",
    "closing",
    "won",
    "lost",
    "nurtured",
]

# Mapping to canonical Lead status
STAGE_TO_LEAD_STATUS = {
    "discovered": "new",
    "qualified": "contacted",
    "researching": "contacted",
    "outreach_ready": "contacted",
    "in_cadence": "contacted",
    "replied": "engaged",
    "meeting_booked": "meeting",
    "proposal": "proposal",
    "closing": "proposal",
    "won": "closed_won",
    "lost": "closed_lost",
    "nurtured": "nurturing",
}


class StageTransitionGatekeeper:
    """Evaluates and executes validated deal stage advancements."""

    def __init__(self, db: Session, tenant_id: str):
        self.db = db
        self.tenant_id = tenant_id

    def evaluate_transition(
        self,
        deal_room: DealRoom,
        target_stage: str,
        loss_reason: Optional[str] = None,
    ) -> Tuple[bool, str, List[str]]:
        """
        Validates whether the deal room meets all entry criteria for target_stage.
        Returns: (allowed, reason, missing_criteria)
        """
        if target_stage not in VALID_STAGES:
            return False, f"Invalid target stage '{target_stage}'.", [f"Must be one of: {', '.join(VALID_STAGES)}"]

        if deal_room.stage == target_stage:
            return True, f"Deal is already in stage '{target_stage}'.", []

        # Lost / Nurtured transitions are always permitted but require explanation if lost
        if target_stage == "lost":
            if not loss_reason or not loss_reason.strip():
                return False, "Moving to 'lost' requires an explicit loss reason.", ["Loss reason is mandatory"]
            return True, "Loss transition authorized.", []

        if target_stage == "nurtured":
            return True, "Nurturing transition authorized.", []

        missing: List[str] = []

        # Criteria: 'qualified'
        if target_stage == "qualified":
            if (deal_room.icp_fit_score or 0.0) < 0.2 and not deal_room.industry:
                missing.append("Account must have either an ICP fit score >= 0.2 or verified industry")

        # Criteria: 'proposal'
        if target_stage in ("proposal", "closing", "won"):
            # Check for at least 1 buying committee member (Champion or Economic Buyer preferred)
            members = (
                self.db.query(BuyingCommitteeMember)
                .filter(
                    BuyingCommitteeMember.deal_room_id == deal_room.id,
                    BuyingCommitteeMember.tenant_id == self.tenant_id,
                )
                .all()
            )
            if not members and not deal_room.domain:
                missing.append("Proposal stage requires at least one identified buying committee contact or verified domain")

        # Criteria: 'closing'
        if target_stage in ("closing", "won"):
            brief = deal_room.account_brief or {}
            latest_quote = brief.get("latest_quote")
            if not latest_quote:
                missing.append("Closing stage requires an active quote generated by Deal Desk")
            elif latest_quote.get("policy_status") == "blocked":
                missing.append("Quote is blocked by commercial pricing policy (Floor price or discount violation)")
            elif latest_quote.get("policy_status") in ("requires_manager_approval", "requires_vp_approval"):
                missing.append("Quote has pending discounts awaiting Manager or VP approval")

        # Criteria: 'won'
        if target_stage == "won":
            brief = deal_room.account_brief or {}
            latest_prop = brief.get("latest_proposal")
            if not latest_prop:
                missing.append("Closed Won requires a generated commercial proposal/contract")

        if missing:
            return False, f"Entry criteria for stage '{target_stage}' not met.", missing

        return True, f"All criteria for '{target_stage}' satisfied.", []

    def execute_transition(
        self,
        deal_room_id: str,
        target_stage: str,
        loss_reason: Optional[str] = None,
        notes: Optional[str] = None,
        user_id: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Atomically advances deal stage across DealRoom, SalesOpportunity, and Lead."""
        deal_room = (
            self.db.query(DealRoom)
            .filter(DealRoom.id == deal_room_id, DealRoom.tenant_id == self.tenant_id)
            .first()
        )
        if not deal_room:
            raise ValueError(f"DealRoom '{deal_room_id}' not found for tenant '{self.tenant_id}'.")

        allowed, reason, missing = self.evaluate_transition(deal_room, target_stage, loss_reason=loss_reason)
        if not allowed:
            return {
                "success": False,
                "deal_room_id": deal_room_id,
                "current_stage": deal_room.stage,
                "target_stage": target_stage,
                "reason": reason,
                "missing_criteria": missing,
            }

        prev_stage = deal_room.stage
        deal_room.stage = target_stage
        deal_room.last_activity_at = datetime.now(timezone.utc)

        # Update metadata if lost
        if target_stage == "lost" and loss_reason:
            meta = dict(deal_room.account_brief or {})
            meta["loss_reason"] = loss_reason
            meta["loss_notes"] = notes
            meta["lost_at"] = datetime.now(timezone.utc).isoformat()
            deal_room.account_brief = meta

        # Synchronize SalesOpportunity
        opp = (
            self.db.query(SalesOpportunity)
            .join(SalesCompany, SalesOpportunity.company_id == SalesCompany.id)
            .filter(
                SalesCompany.canonical_domain == deal_room.domain,
                SalesOpportunity.tenant_id == self.tenant_id,
            )
            .first()
        )
        if opp:
            opp.stage = target_stage
            opp.updated_at = datetime.now(timezone.utc)

        # Synchronize linked Leads
        lead_status = STAGE_TO_LEAD_STATUS.get(target_stage, "contacted")
        leads_query = self.db.query(Lead).filter(Lead.tenant_id == self.tenant_id)
        if opp:
            leads = leads_query.filter(
                (Lead.sales_opportunity_id == opp.id) | (Lead.company == deal_room.company_name)
            ).all()
        else:
            leads = leads_query.filter(Lead.company == deal_room.company_name).all()
        for ld in leads:
            ld.status = lead_status

        # Create DealActivity Audit Log
        activity = DealActivity(
            deal_room_id=deal_room.id,
            tenant_id=self.tenant_id,
            activity_type="stage_changed",
            channel="sales_os",
            direction="internal",
            subject=f"Stage advanced: {prev_stage} → {target_stage}",
            content=f"Deal stage updated from '{prev_stage}' to '{target_stage}'. Reason: {notes or reason}",
            metadata_json={
                "prev_stage": prev_stage,
                "next_stage": target_stage,
                "user_id": user_id,
                "loss_reason": loss_reason,
            },
        )
        self.db.add(activity)
        self.db.commit()

        return {
            "success": True,
            "deal_room_id": deal_room.id,
            "previous_stage": prev_stage,
            "current_stage": target_stage,
            "lead_status_synced": lead_status,
            "leads_synced_count": len(leads),
            "reason": reason,
        }
