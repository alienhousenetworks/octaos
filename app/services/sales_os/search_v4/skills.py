def resolve_request(text: str, granted_permissions: set[str] | list[str], level: int = 1) -> dict:
    """Resolve a request to a known skill and the disclosure level that was granted."""
    granted = set(granted_permissions or [])
    lowered = (text or "").lower()
    skill_id = "discovery.plan_queries"
    for needle, candidate in _REQUESTS:
        if needle in lowered:
            skill_id = candidate
            break
    skill = SALES_SKILLS[skill_id]
    missing = [permission for permission in skill.required_permissions if permission not in granted]
    if missing:
        return {
            "status": "denied",
            "skill_id": skill.skill_id,
            "missing_permissions": missing,
            "disclosure": "",
        }
    if level <= 1:
        disclosure = f"Skill `{skill.skill_id}`: {skill.description}"
    elif level == 2:
        disclosure = (
            f"Skill: {skill.skill_id}\n"
            f"Version: {skill.version}\n"
            f"Agent: {skill.agent_class or 'deterministic service'}\n"
            f"Permissions: {', '.join(skill.required_permissions)}"
        )
    else:
        disclosure = (
            f"{skill.description}\n"
            "Procedural guidance stays inside the registered agent. "
            "This text does not grant tools, approval, or permission to send."
        )
    return {
        "status": "resolved",
        "skill_id": skill.skill_id,
        "version": skill.version,
        "agent_class": skill.agent_class,
        "deterministic": skill.deterministic,
        "approval_required": skill.approval_required,
        "contract_id": skill.contract_id,
        "disclosure": disclosure,
        "executed": False,
    }
