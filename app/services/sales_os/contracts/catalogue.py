_LLM = LlmConfig(provider="anthropic", model_id="claude-3-haiku-20240307", temperature=0.0, max_tokens=1200)
_FAIL = FailurePolicy()


def _code(
    agent_id: str,
    purpose: str,
    *,
    status: LifecycleStatus = LifecycleStatus.active,
    reads: list[str] | None = None,
    writes: list[str] | None = None,
    evaluation: list[str] | None = None,
    policy: list[str] | None = None,
    approval: list[str] | None = None,
) -> AgentContract:
    return AgentContract(
        agent_id=agent_id,
        version="1.0.0",
        purpose=purpose,
        lifecycle_status=status,
        uses_llm=False,
        data_permissions=DataPermissions(reads=reads or [], writes=writes or []),
        tool_permissions=ToolPermissions(allowed=[], external_actions=False),
        evidence_requirements=EvidenceRequirements(),
        policy_requirements=policy or ["tenant_isolation"],
        timeout_and_retry=TimeoutRetry(timeout_seconds=15, max_attempts=1),
        idempotency=IdempotencySpec(key_fields=["tenant_id", "input_snapshot_hash", "version"]),
        evaluation_suite=evaluation or ["schema_validity", "tenant_isolation"],
        failure_policy=_FAIL,
        approval_requirements=approval or [],
    )


def _llm(
    agent_id: str,
    purpose: str,
    system,
    task,
    *,
    status: LifecycleStatus = LifecycleStatus.active,
    reads: list[str] | None = None,
    writes: list[str] | None = None,
    variables: dict | None = None,
    extra_tasks: dict | None = None,
    evaluation: list[str] | None = None,
    output_schema: dict | None = None,
    llm: LlmConfig | None = None,
    approval: list[str] | None = None,
    policy: list[str] | None = None,
) -> AgentContract:
    return AgentContract(
        agent_id=agent_id,
        version="1.0.0",
        purpose=purpose,
        lifecycle_status=status,
        uses_llm=True,
        system_prompt=system,
        prompt_version=system.version,
        prompt_variables_schema=variables or {"type": "object", "properties": {}, "required": []},
        task_prompt_template=task,
        task_prompts=extra_tasks or {},
        output_schema=output_schema or {"type": "object"},
        data_permissions=DataPermissions(reads=reads or [], writes=writes or []),
        tool_permissions=ToolPermissions(allowed=[], external_actions=False),
        evidence_requirements=EvidenceRequirements(),
        policy_requirements=policy or ["tenant_isolation", "output_schema_validation"],
        timeout_and_retry=TimeoutRetry(timeout_seconds=60, max_attempts=2),
        idempotency=IdempotencySpec(),
        evaluation_suite=evaluation
        or ["factual_grounding", "schema_validity", "tenant_isolation", "failure_abstention"],
        llm_config=llm or _LLM,
        failure_policy=_FAIL,
        approval_requirements=approval or [],
    )


def _vars(*required: str) -> dict:
    return {
        "type": "object",
        "required": list(required),
        "properties": {name: {"type": "string"} for name in required},
    }


