export async function fetchCatalog(
  apiUrl: string,
  fetchWithAuth: (url: string, options?: any) => Promise<Response>,
  mode: CanvasMode | 'all' = 'general'
): Promise<NodeCategory[]> {
  try {
    const res = await fetchWithAuth(`${apiUrl}/automation-nodes/catalog?mode=${mode}`);
    if (res.ok) {
      const data = await res.json();
      if (Array.isArray(data) && data.length > 0) {
        return data;
      }
    }
  } catch (e) {
    console.warn('Failed to fetch remote catalog, falling back to static catalog', e);
  }

  // Filter static catalog based on mode
  if (mode === 'all') return STATIC_ENTERPRISE_CATALOG;
  return STATIC_ENTERPRISE_CATALOG.map((cat) => ({
    ...cat,
    families: cat.families
      .map((fam) => ({
        ...fam,
        nodes: fam.nodes.filter(
          (node) => node.mode === 'all' || node.mode === mode
        ),
      }))
      .filter((fam) => fam.nodes.length > 0),
  })).filter((cat) => cat.families.length > 0);
}
